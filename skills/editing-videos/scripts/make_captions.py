"""Burned-in captions from the rough cut's word timings, written as ASS subtitles.

ASS (Advanced SubStation Alpha) supports fonts, colours, positioning and small animations;
render.py burns it into the picture. The default look is the common short-form style: a few
words at a time, the word being spoken highlighted, each new group popping in.

Usage:
    python make_captions.py <rough_cut.words.json> <captions.ass>
        [--max-words 3] [--font "Inter"] [--size 0.075] [--color FFFFFF]
        [--highlight FFD400 | --highlight none] [--position bottom|middle|top]
        [--bottom-margin 0.30] [--uppercase] [--animation pop|none] [--outline 6]

Colours are RRGGBB hex. Sizes are fractions of the frame's short side.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from media_utils import read_json  # noqa: E402

SENTENCE_END = (".", "!", "?", "…", ":")
# A speaking pause longer than this starts a new caption group.
NEW_GROUP_PAUSE = 0.45
# Shorter gaps between groups are bridged so captions don't flicker off and on.
BRIDGE_GAP = 0.30
# How long the last group stays on screen when the speaker pauses.
LINGER = 0.25
# Captions are authored on a canvas whose short side is 1080 px; libass scales to the real size.
CANVAS_SHORT_SIDE = 1080


def ass_style_color(rgb_hex: str, opacity: float = 1.0) -> str:
    """Style colours are &HAABBGGRR (alpha first, then blue-green-red; alpha 00 = opaque)."""
    rgb_hex = rgb_hex.lstrip("#")
    alpha = f"{int(round((1 - opacity) * 255)):02X}"
    return f"&H{alpha}{rgb_hex[4:6]}{rgb_hex[2:4]}{rgb_hex[0:2]}".upper()


def ass_inline_color(rgb_hex: str) -> str:
    """Inline colour overrides are written &HBBGGRR&."""
    rgb_hex = rgb_hex.lstrip("#")
    return f"&H{rgb_hex[4:6]}{rgb_hex[2:4]}{rgb_hex[0:2]}&".upper()


def ass_time(seconds: float) -> str:
    centis = int(round(max(0.0, seconds) * 100))
    hours, rest = divmod(centis, 360000)
    minutes, rest = divmod(rest, 6000)
    secs, cs = divmod(rest, 100)
    return f"{hours}:{minutes:02d}:{secs:02d}.{cs:02d}"


def escape_text(text: str) -> str:
    return text.replace("\\", "/").replace("{", "(").replace("}", ")")


def build_groups(words: list[dict], max_words: int) -> list[list[dict]]:
    groups: list[list[dict]] = []
    for word in words:
        if (not groups or len(groups[-1]) >= max_words or groups[-1][-1]["word"].endswith(SENTENCE_END)
                or word["start"] - groups[-1][-1]["end"] > NEW_GROUP_PAUSE):
            groups.append([word])
        else:
            groups[-1].append(word)
    return groups


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate ASS captions from word timings.")
    parser.add_argument("words", type=Path, help="*.words.json from render_rough_cut.py")
    parser.add_argument("output", type=Path, help="e.g. work/captions.ass")
    parser.add_argument("--max-words", type=int, default=3)
    parser.add_argument("--font", default="Noto Sans", help="installed font name, or one in --fonts-dir at render time")
    parser.add_argument("--size", type=float, default=0.075, help="font size as a fraction of the short side")
    parser.add_argument("--color", default="FFFFFF")
    parser.add_argument("--highlight", default="FFD400", help="colour of the spoken word, or 'none'")
    parser.add_argument("--outline-color", default="000000")
    parser.add_argument("--outline", type=float, default=6, help="outline thickness in canvas pixels")
    parser.add_argument("--position", choices=["bottom", "middle", "top"], default="bottom")
    parser.add_argument("--bottom-margin", type=float, default=0.30,
                        help="for 'bottom': distance from the bottom edge as a fraction of the height. "
                             "0.30 keeps vertical-video captions clear of TikTok/Reels/Shorts controls")
    parser.add_argument("--uppercase", action="store_true")
    parser.add_argument("--regular-weight", action="store_true", help="use regular instead of bold")
    parser.add_argument("--animation", choices=["pop", "none"], default="pop")
    args = parser.parse_args()

    data = read_json(args.words)
    words = [w for w in data["words"] if w["word"].strip()]
    if not words:
        sys.exit("No words found. Was the rough cut rendered from a cut list with transcripts?")

    scale = CANVAS_SHORT_SIDE / min(data["width"], data["height"])
    canvas_w, canvas_h = round(data["width"] * scale), round(data["height"] * scale)
    font_size = round(CANVAS_SHORT_SIDE * args.size)
    alignment = {"bottom": 2, "middle": 5, "top": 8}[args.position]
    margin_v = round(canvas_h * (args.bottom_margin if args.position == "bottom" else 0.12))
    margin_h = round(canvas_w * 0.08)

    header = f"""[Script Info]
; Generated by make_captions.py
ScriptType: v4.00+
PlayResX: {canvas_w}
PlayResY: {canvas_h}
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Caption,{args.font},{font_size},{ass_style_color(args.color)},{ass_style_color(args.color)},{ass_style_color(args.outline_color)},{ass_style_color('000000', 0.45)},{0 if args.regular_weight else -1},0,0,0,100,100,0,0,1,{args.outline},2,{alignment},{margin_h},{margin_h},{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events = []
    groups = build_groups(words, args.max_words)
    for index, group in enumerate(groups):
        start = group[0]["start"]
        next_start = groups[index + 1][0]["start"] if index + 1 < len(groups) else None
        end = group[-1]["end"] + LINGER
        if next_start is not None and (next_start - group[-1]["end"] <= BRIDGE_GAP or end > next_start):
            end = next_start
        texts = [escape_text(w["word"].upper() if args.uppercase else w["word"]) for w in group]
        pop = r"{\fscx82\fscy82\t(0,90,\fscx100\fscy100)}" if args.animation == "pop" else ""

        if args.highlight.lower() == "none":
            events.append(f"Dialogue: 0,{ass_time(start)},{ass_time(end)},Caption,,0,0,0,,{pop}{' '.join(texts)}")
            continue
        # One event per word: same group, with the word currently being spoken recoloured.
        active = ass_inline_color(args.highlight)
        for position, word in enumerate(group):
            word_start = start if position == 0 else word["start"]
            word_end = group[position + 1]["start"] if position + 1 < len(group) else end
            parts = [rf"{{\c{active}}}{t}{{\r}}" if i == position else t for i, t in enumerate(texts)]
            events.append(f"Dialogue: 0,{ass_time(word_start)},{ass_time(word_end)},Caption,,0,0,0,,"
                          f"{pop if position == 0 else ''}{' '.join(parts)}")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header + "\n".join(events) + "\n", encoding="utf-8")
    print(f"{len(groups)} caption groups from {len(words)} words → {args.output}")


if __name__ == "__main__":
    main()
